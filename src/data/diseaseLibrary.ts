export const getDiseaseById = (id: string): Disease | undefined =>
  diseaseLibrary.find((d) => d.id === id);

export const getDiseasesByPlant = (plant: string): Disease[] =>
  diseaseLibrary.filter((d) => d.plant.toLowerCase() === plant.toLowerCase());

export const getDiseasesBySeverity = (severity: Disease["severity"]): Disease[] =>
  diseaseLibrary.filter((d) => d.severity === severity);

export const getUniquePlants = (): string[] =>
  [...new Set(diseaseLibrary.map((d) => d.plant))];
